export function createItem(id: string, count = 1): Item {
  const def = ITEM_DEFS[id];
  if (!def) {
    return {
      id,
      name: id.toUpperCase(),
      type: "trash",
      description: "Unknown item",
      count,
      price: 0,
      iconColor: "#7f8c8d",
    };
  }
  return { ...def, count };
}
